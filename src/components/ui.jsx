// Decorative by default (aria-hidden). Buttons that contain only an icon must have an aria-label.
export function Icon({ name, size = 20 }) {
  return (
    <svg className="icon" width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2"
      strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" focusable="false">
      {ICONS[name] ?? null}
    </svg>
  );
}

// The ExpenseX mark + HTML wordmark + "Corporate" label.
